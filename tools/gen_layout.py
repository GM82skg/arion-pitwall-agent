"""Generates src/lmu/layout.rs from pyLMUSharedMemory (TinyPedal), itself a port of S397's
SharedMemoryInterface header. Every field offset and every struct size is written into a Rust test,
so `cargo test` proves the Rust layout matches byte for byte.
pyLMUSharedMemory: MIT License, (c) 2021 Tony Whitley, (c) 2025 Xiang — see THIRD-PARTY.md."""
import ctypes, sys, inspect
sys.path.insert(0, sys.argv[1])
import importlib
lmu = importlib.import_module('pyLMUSharedMemory.lmu_data')
PRIM = {ctypes.c_double:'f64', ctypes.c_float:'f32', ctypes.c_int:'i32', ctypes.c_uint:'u32', ctypes.c_short:'i16',
        ctypes.c_ushort:'u16', ctypes.c_ubyte:'u8', ctypes.c_uint8:'u8', ctypes.c_byte:'i8', ctypes.c_bool:'u8',
        ctypes.c_char:'u8', ctypes.c_ulonglong:'u64'}
def rty(t):
    if t in PRIM: return PRIM[t]
    if issubclass(t, ctypes.Array): return f'[{rty(t._type_)}; {t._length_}]'
    if issubclass(t, ctypes.Structure): return t.__name__
    raise SystemExit(f'unknown type {t}')
structs = [c for _, c in inspect.getmembers(lmu, inspect.isclass) if issubclass(c, ctypes.Structure) and c.__module__ == lmu.__name__]
order, seen = [], set()
def visit(c):
    if c in seen: return
    seen.add(c)
    for _, t in c._fields_:
        while issubclass(t, ctypes.Array): t = t._type_
        if isinstance(t, type) and issubclass(t, ctypes.Structure): visit(t)
    order.append(c)
for c in structs: visit(c)
out = ['// GENERATED by tools/gen_layout.py from pyLMUSharedMemory (MIT, (c) 2021 Tony Whitley, (c) 2025 Xiang; see THIRD-PARTY.md),',
       '// a port of the SharedMemoryInterface header by Studio 397.',
       '// Do not edit by hand. pack(4) as in the header. c_bool is read as u8 (any non-zero = true).',
       '#![allow(non_snake_case, non_camel_case_types, dead_code, clippy::all)]', '']
tests = ['#[cfg(test)]', 'mod layout_tests {', '    use super::*;', '    use std::mem::{offset_of, size_of};', '    #[test]', '    fn every_struct_and_field_matches_the_header() {']
for c in order:
    out += ['#[repr(C, packed(4))]', '#[derive(Clone, Copy)]', f'pub struct {c.__name__} {{']
    for n, t in c._fields_:
        out.append(f'    pub {n}: {rty(t)},')
        tests.append(f'        assert_eq!(offset_of!({c.__name__}, {n}), {getattr(c, n).offset}, "{c.__name__}.{n}");')
    out += ['}', '']
    tests.append(f'        assert_eq!(size_of::<{c.__name__}>(), {ctypes.sizeof(c)}, "size of {c.__name__}");')
tests += ['    }', '}']
consts = [f'pub const MAX_MAPPED_VEHICLES: usize = {lmu.LMUConstants.MAX_MAPPED_VEHICLES};',
          f'pub const SHARED_MEMORY_NAME: &str = "{lmu.LMUConstants.LMU_SHARED_MEMORY_FILE}";',
          f'pub const LAYOUT_SIZE: usize = {ctypes.sizeof(lmu.LMULayout)};', '']
open(sys.argv[2], 'w').write('\n'.join(out[:4] + consts + out[4:] + tests) + '\n')
print('structs', len(order), 'layout size', ctypes.sizeof(lmu.LMULayout))
